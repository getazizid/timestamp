export function getRandomIndonesianAddress(): {
  province: string;
  city: string;
  district: string;
  street: string;
  formattedAddress: string;
  lat: number;
  lng: number;
} {
  const randomReg = INDONESIAN_REGIONS[Math.floor(Math.random() * INDONESIAN_REGIONS.length)];
  const randomStreet = SAMPLE_STREETS[Math.floor(Math.random() * SAMPLE_STREETS.length)];
  const randomDistrict = SAMPLE_DISTRICTS[Math.floor(Math.random() * SAMPLE_DISTRICTS.length)];

  // Slight jitter for realism
  const lat = parseFloat((randomReg.lat + (Math.random() - 0.5) * 0.02).toFixed(6));
  const lng = parseFloat((randomReg.lng + (Math.random() - 0.5) * 0.02).toFixed(6));

  const formattedAddress = `${randomStreet}, ${randomDistrict}, ${randomReg.city}, ${randomReg.province}, Indonesia`;

  return {
    province: randomReg.province,
    city: randomReg.city,
    district: randomDistrict,
    street: randomStreet,
    formattedAddress,
    lat,
    lng
  };
}
